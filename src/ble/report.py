"""reports/EVALUATION.md from the JSON reports."""

from __future__ import annotations

import json
from typing import Any

from ble.config import REPORTS

NAMES = {
    "missing_price": "Missing price",
    "included_price": "Priced as included",
    "arithmetic_error": "Arithmetic error (EP × qty ≠ total)",
    "qty_changed": "Quantity changed",
    "unit_changed": "Unit changed",
    "missing_position": "Position not priced",
    "extra_position": "Position added",
    "spec_change": "Long text changed (spec)",
    "product_alternative": "Other product than reference",
    "price_outlier": "Unit price outlier",
    "speculative_pricing": "Speculative (unbalanced) pricing",
    "outdated_version": "Priced an outdated BoQ version",
    "reservation": "Reservation in cover letter",
}


def _read(name: str) -> Any:
    p = REPORTS / name
    return json.loads(p.read_text()) if p.exists() else None


def _p(x: float | None) -> str:
    return "–" if x is None else f"{100 * x:.1f}%"


def write_report() -> str:
    L = [
        "# Evaluation",
        "",
        "Generated by `ble run`. Every number comes from the JSON files in this folder; the data is simulated (see the README for what that leaves out).",
        "",
    ]
    for split in ("test", "dev"):
        ev = _read(f"eval_{split}.json")
        if not ev:
            continue
        t = ev["total"]
        L += [
            f"## Findings on the {split} tenders",
            "",
            f"Precision **{_p(t['precision'])}**, recall **{_p(t['recall'])}** ({t['tp']} found, {t['fp']} false, {t['fn']} missed).",
            "",
        ]
        L += ["| Deviation | Found | False | Missed | Precision | Recall |", "|---|---|---|---|---|---|"]
        for k, v in ev["findings"].items():
            if v["tp"] + v["fp"] + v["fn"]:
                L.append(f"| {NAMES.get(k, k)} | {v['tp']} | {v['fp']} | {v['fn']} | {_p(v['precision'])} | {_p(v['recall'])} |")
        L += ["", "| How the bid arrived | Found | False | Missed | Precision | Recall |", "|---|---|---|---|---|---|"]
        for k, v in ev["by_route"].items():
            L.append(f"| {k} | {v['tp']} | {v['fp']} | {v['fn']} | {_p(v['precision'])} | {_p(v['recall'])} |")
        rv = ev["review"]
        auto = rv.get("true_auto", 0) + rv.get("false_auto", 0)
        rq = rv.get("true_needs_review", 0) + rv.get("false_needs_review", 0)
        L += [
            "",
            f"Review routing: {auto} findings were confident enough to auto-confirm, of which {rv.get('false_auto', 0)} were wrong; {rq} went to review, of which {rv.get('false_needs_review', 0)} were wrong.",
            "",
        ]
        L += [
            "**Matching bid lines to BoQ positions**",
            "",
            "| Route | Lines | Correct | By position number alone | Sent to review | Wrong and not flagged |",
            "|---|---|---|---|---|---|",
        ]
        for k, v in ev["matching"].items():
            L.append(f"| {k} | {v['lines']} | {_p(v['accuracy'])} | {_p(v['oz_only_accuracy'])} | {v.get('review', 0)} | {v.get('wrong_not_flagged', 0)} |")
        v = ev["versions"]
        L += ["", f"BoQ version each bid priced, identified correctly: {v.get('correct', 0)} of {v.get('correct', 0) + v.get('wrong', 0)}.", ""]
        if ev.get("false_alarms"):
            L += (
                ["<details><summary>False findings</summary>", ""]
                + [f"- {x['bid']} ({x['route']}): {x['type']} {x['oz'] or ''} – {x['message']}" for x in ev["false_alarms"][:30]]
                + ["", "</details>", ""]
            )
        if ev.get("misses"):
            L += (
                ["<details><summary>Missed deviations</summary>", ""]
                + [f"- {x['bid']} ({x['route']}): {x['type']} {x['oz'] or ''} – {x['detail']}" for x in ev["misses"][:30]]
                + ["", "</details>", ""]
            )
    d = _read("eval_test_default_matcher.json")
    if d:
        L += ["## Fitted matcher against hand-set weights (test tenders)", "", "| Route | Fitted | Hand-set |", "|---|---|---|"]
        ev = _read("eval_test.json")
        for k, v in d["matching"].items():
            L.append(f"| {k} | {_p(ev['matching'][k]['accuracy'])} | {_p(v['accuracy'])} |")
        L.append("")
    s = _read("search.json")
    if s:
        L += [
            "## Searching a BoQ in German",
            "",
            "Queries the way estimators type them (compounds split or joined, shorthand, no umlauts) against each tender's positions.",
            "",
            "| Tokenizer | Split | Queries | Hit@1 | Hit@3 |",
            "|---|---|---|---|---|",
        ]
        for split in ("test", "dev"):
            for name, v in s[split].items():
                L.append(f"| {name} | {split} | {v['queries']} | {_p(v['hit@1'])} | {_p(v['hit@3'])} |")
        L.append("")
    ing = _read("ingest.json")
    if ing:
        L += ["## Ingestion", "", "| Route | Bids | Pages | Pages per minute | € per page |", "|---|---|---|---|---|"]
        for k, v in ing.items():
            L.append(f"| {k} | {v['bids']} | {v['pages']} | {v['pages_per_minute']} | {v['eur_per_page']} |")
        L.append("")
    sets = sorted(p.parent.name for p in (REPORTS / "heldout").glob("*/first_run.json")) if (REPORTS / "heldout").exists() else []
    if sets:
        L += [
            "## Held-out sets",
            "",
            "Bids written by an agent that never saw the engine (set v1: BoQs by the engine's author; from v2 the BoQs are blind too).",
            "The first run of each set is kept as written. A set whose failures were studied becomes a regression set;",
            "its later runs (`latest.json`) show the fixes, and only a new set measures the engine again.",
            "",
            "| Set | Status | Run | Precision | Recall | Wrong findings auto-confirmed |",
            "|---|---|---|---|---|---|",
        ]
        for v in sets:
            status = (REPORTS.parent / "heldout" / v / "STATUS").read_text().strip() if (REPORTS.parent / "heldout" / v / "STATUS").exists() else "held out"
            for run, name in (("first_run", "first run"), ("latest", "latest")):
                ho = _read(f"heldout/{v}/{run}.json")
                if ho:
                    t, rv = ho["score"]["total"], ho["score"].get("review", {})
                    auto = rv.get("true_auto", 0) + rv.get("false_auto", 0)
                    L.append(
                        f"| [{v}](heldout/{v}/FIRST_RUN.md) | {status} | {name} | {_p(t['precision'])} | {_p(t['recall'])} | {rv.get('false_auto', 0)} of {auto} |"
                    )
        L.append("")
    g = _read("gate.json")
    if g:
        L += (
            ["## Gate", "", "| Check | Result | Detail |", "|---|---|---|"]
            + [f"| {c['check']} | {'pass' if c['passed'] else 'FAIL'} | {c['detail']} |" for c in g["checks"]]
            + [""]
        )
    text = "\n".join(L)
    (REPORTS / "EVALUATION.md").write_text(text, encoding="utf-8")
    return text
